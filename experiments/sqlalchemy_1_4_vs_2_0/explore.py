"""
explore.py — SQLAlchemy 1.4 relationship behaviour, watched rather than asserted.

Every relationship pattern in models.py gets seeded with a small, hand-traceable
dataset, then printed — so you can see what the ORM actually did: which rows
appeared, which foreign keys it filled in for you, and which SQL it emitted.

Run:  uv run python -m experiments.sqlalchemy_1_4_vs_2_0.explore

Written in 1.4 style on purpose (session.query(...), backref, etc.). Those are the
idioms Phase 0 migrates to 2.0 later, so they stay exactly as they are.
"""

from datetime import datetime

from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker

from experiments.sqlalchemy_1_4_vs_2_0 import models


def section(title):
    print()
    print("=" * 72)
    print(title)
    print("=" * 72)


# ---------------------------------------------------------------------------
# Setup
# ---------------------------------------------------------------------------
# "sqlite://" with no path = in-memory database. It exists only while this
# process runs, which is what you want for an experiment: every run starts clean.
engine = create_engine("sqlite://")
models.Base.metadata.create_all(engine)

# sessionmaker is a CLASS; Session is an INSTANCE of it (a configured, callable
# factory); session is the actual Session object that talks to the database.
Session = sessionmaker(bind=engine)
session = Session()


# ---------------------------------------------------------------------------
# 1. Users and Project — flush() vs primary keys
# ---------------------------------------------------------------------------
section("1. Users + Project — where do primary keys come from?")

alice = models.User(name="Alice", email="alice@example.com")
bob = models.User(name="Bob", email="bob@example.com")
apollo = models.Project(name="Apollo", created_at=datetime(2026, 1, 15, 9, 0))

print("before add   ->", alice.id, bob.id, apollo.id)

session.add_all([alice, bob, apollo])
# add() only *stages* the objects. No SQL has run yet, so still no ids.
print("after add    ->", alice.id, bob.id, apollo.id)

session.flush()
# flush() emits the INSERTs and reads the generated keys back onto the objects.
# It does NOT end the transaction — everything so far is still rollback-able.
print("after flush  ->", alice.id, bob.id, apollo.id)
print("note: alice.id and apollo.id are both 1 — different tables, separate counters.")


# ---------------------------------------------------------------------------
# 2. Issues — one-to-many, and the save-update cascade
# ---------------------------------------------------------------------------
section("2. Issues — one-to-many, two ways to attach, zero manual FK writes")

# Nine issues, so the ids referenced in study/01-CONCEPTS.md Part 3 (3, 7, 9) exist.
TITLES = [
    ("Login page returns 500 on submit", "open"),
    ("Dashboard widgets load out of order", "open"),
    ("Export button missing for read-only users", "open"),
    ("Search returns stale results after an edit", "open"),
    ("Email notifications sent twice", "closed"),
    ("Timezone shown in UTC on issue detail", "open"),
    ("Bulk close times out past 50 issues", "open"),
    ("Avatar upload rejects PNG over 2MB", "closed"),
    ("Filter state lost on browser back", "open"),
]

# Style A: set the child's parent. `.project` is NOT declared on Issue — it is
# generated by `backref="project"` over on the Project class.
issue1 = models.Issue(
    title=TITLES[0][0], status=TITLES[0][1], created_at=datetime(2026, 2, 1, 10, 30)
)
issue1.project = apollo

# Style B: append to the parent's collection. Same relationship, other end.
issues = [issue1]
for n, (title, status) in enumerate(TITLES[1:], start=2):
    iss = models.Issue(
        title=title, status=status, created_at=datetime(2026, 2, n, 9, 0)
    )
    apollo.issues.append(iss)
    issues.append(iss)

# Named handles for the ones Part 3 talks about.
issue2, issue3, issue7, issue9 = issues[1], issues[2], issues[6], issues[8]

# None of the nine were passed to session.add(). They got pulled in anyway:
# the default "save-update" cascade enrolls anything attached to an object that
# is already in the session.
#
# 2.0 CAVEAT: only the direction used just above survives. These issues are
# attached with apollo.issues.append(iss) — the collection side — which 2.0
# keeps. The many-to-one side used further down (c2.issue = issue1,
# a1.user = alice, and issue1.project = apollo on line 88) relies on the
# backref leg, which 2.0 drops SILENTLY: those objects would never be
# inserted and nothing would be raised. Measured in migration.py §8.
print("issue1 in session?", issue1 in session)
print("issue9 in session?", issue9 in session)
print("objects staged for INSERT:", len(session.new))

session.flush()
print("project_id values ->", [i.project_id for i in issues])
print("...never assigned by hand. SQLAlchemy resolved the object reference to an int.")
print("issue ids ->", [i.id for i in issues])


# ---------------------------------------------------------------------------
# 3. Labels — many-to-many via a secondary table
# ---------------------------------------------------------------------------
section("3. Labels — many-to-many writes rows to a THIRD table")

bug = models.Label(name="bug")
urgent = models.Label(name="urgent")
ui = models.Label(name="ui")

# Neither Issue nor Label has a column pointing at the other. The only place
# this link can live is a new row in the issue_labels association table.
issue1.labels.append(bug)
issue1.labels.append(urgent)
issue2.labels.append(ui)
issue3.labels.append(bug)
issue3.labels.append(ui)
issue7.labels.append(urgent)

session.flush()

print("issue_labels rows ->", session.execute(models.issue_labels.select()).fetchall())
print("  (issue_id, label_id)")
print("issue3.labels ->", issue3.labels)
print("bug.issues    ->", bug.issues, "  <- reverse side, from backref='issues'")


# ---------------------------------------------------------------------------
# 4. Comments — a child with TWO parents
# ---------------------------------------------------------------------------
section("4. Comments — two foreign keys, two backrefs from two different classes")

c1 = models.Comment(
    body="Reproduced on staging — stack trace points at the session middleware.",
    created_at=datetime(2026, 2, 1, 11, 15),
)
c1.issue = issue1     # `.issue`  generated by backref on Issue.comments
c1.author = alice     # `.author` generated by backref on User.comments

c2 = models.Comment(
    body="Patch is up, needs review.",
    created_at=datetime(2026, 2, 2, 9, 0),
)
c2.issue = issue1
c2.author = bob

c3 = models.Comment(
    body="Permission check reads the wrong role field.",
    created_at=datetime(2026, 2, 5, 16, 20),
)
c3.issue = issue3
c3.author = alice

session.flush()

# Worth noticing: Comment's class body declares neither `.issue` nor `.author`.
# Both attributes were injected onto it from *other* classes' backref= arguments.
print("c3 ->", c3, "| author:", c3.author, "| issue:", c3.issue)
print("issue1.comments ->", issue1.comments)
print("alice.comments  ->", alice.comments)


# ---------------------------------------------------------------------------
# 5. IssueAssignment — the association OBJECT (many-to-many with a payload)
# ---------------------------------------------------------------------------
section("5. IssueAssignment — why this one can't use secondary=")

# issue_labels is a bare Table because the link carries no information: an issue
# either has a label or it doesn't. issue_assignments is different — the link
# itself has attributes (role, assigned_at). secondary= gives you no place to put
# those, because it hands you the *target* objects (User) and hides the join row
# entirely. So the join row is promoted to a real mapped class.
a1 = models.IssueAssignment(role="owner", assigned_at=datetime(2026, 2, 1, 10, 35))
a1.issue = issue1
a1.user = alice

a2 = models.IssueAssignment(role="reviewer", assigned_at=datetime(2026, 2, 2, 9, 5))
a2.issue = issue1
a2.user = bob

# Same two users on issue 3, opposite roles — the composite PK is
# (issue_id, user_id), so the same person may appear on many issues and the
# same issue may carry many people, but never the same pair twice.
a3 = models.IssueAssignment(role="owner", assigned_at=datetime(2026, 2, 4, 9, 0))
a3.issue = issue3
a3.user = bob

session.flush()

print("issue3.assignments ->", issue3.assignments)
print("issue3.assignments[0].role ->", issue3.assignments[0].role)
print("issue3.assignments[0].user ->", issue3.assignments[0].user)
print("alice.assignments  ->", alice.assignments)
print()
print("The cost: no direct issue.users shortcut. You traverse one hop further —")
for a in issue1.assignments:
    print(f"   {a.user.name:6} is {a.role} on issue {a.issue_id}")


# ---------------------------------------------------------------------------
# 6. Self-referential many-to-many — the primaryjoin/secondaryjoin swap
# ---------------------------------------------------------------------------
section("6. blocks / blocked_by — one table read in two directions")

# Deliberately asymmetric so the swap has something to prove:
#   issue 9 sits on BOTH sides (it blocks 7, and is blocked by 3)
#   issue 3 blocks two things and is blocked by nothing
#   issue 7 is blocked by two things and blocks nothing
issue3.blocks.append(issue7)   # row (3, 7)
issue3.blocks.append(issue9)   # row (3, 9)
issue9.blocks.append(issue7)   # row (9, 7)

session.flush()

print("issue_blocks rows ->", session.execute(models.issue_blocks.select()).fetchall())
print("  (blocker_id, blocked_id)")
print()
print("issue3.blocks     ->", issue3.blocks)
print("issue3.blocked_by ->", issue3.blocked_by, "  <- empty: nothing blocks issue 3")
print("issue7.blocks     ->", issue7.blocks, "  <- empty: issue 7 blocks nothing")
print("issue7.blocked_by ->", issue7.blocked_by)
print("issue9.blocks     ->", issue9.blocks, "  <- issue 9 is on BOTH sides:")
print("issue9.blocked_by ->", issue9.blocked_by)
print()
print("Why those differ — the join conditions themselves, straight off the mapper.")
print("You wrote only the first pair; backref='blocked_by' generated the second:")
print()
_rels = models.Issue.__mapper__.relationships
for _name in ("blocks", "blocked_by"):
    _r = _rels[_name]
    print(f"  Issue.{_name}")
    print(f"     primaryjoin   (me -> junction) : {_r.primaryjoin}")
    print(f"     secondaryjoin (junction -> them): {_r.secondaryjoin}")
print()
print("Same two conditions, opposite order. Had backref reused them unswapped,")
print("blocked_by would filter on blocker_id too and return exactly what blocks")
print("returns — two names for one direction, and no way to ask 'who blocks me?'")


# ---------------------------------------------------------------------------
# 7. Commit, then watch a lazy load actually happen
# ---------------------------------------------------------------------------
section("7. commit() + lazy loading — where N+1 queries come from")

session.commit()

# expire_on_commit defaults to True: after commit, every loaded attribute is
# marked stale, so the next attribute access re-queries the database.
engine.echo = True
print(">>> touching apollo.name (object was expired by commit):")
_ = apollo.name

print()
print(">>> touching apollo.issues (relationship, lazy='select' by default):")
_ = apollo.issues

print()
print(">>> now one SELECT per issue, just to read labels — this is N+1:")
for issue in apollo.issues:
    _ = issue.labels

print()
print(">>> the two self-ref directions, so you can diff the SQL:")
session.expire(issue3)
session.expire(issue7)
_ = issue3.blocks
_ = issue7.blocked_by
engine.echo = False


# ---------------------------------------------------------------------------
# 8. Final tally
# ---------------------------------------------------------------------------
section("8. Row counts")

print("users             ", session.query(models.User).count())
print("projects          ", session.query(models.Project).count())
print("issues            ", session.query(models.Issue).count())
print("labels            ", session.query(models.Label).count())
print("comments          ", session.query(models.Comment).count())
print("issue_assignments ", session.query(models.IssueAssignment).count())
print("issue_labels      ", len(session.execute(models.issue_labels.select()).fetchall()))
print("issue_blocks      ", len(session.execute(models.issue_blocks.select()).fetchall()))

session.close()
